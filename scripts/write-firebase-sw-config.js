#!/usr/bin/env node
/**
 * Writes public/__firebase-sw-config.js for the service worker (FCM).
 * Merges .env with process.env so CI can inject REACT_APP_* without a file.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function loadEnvFile() {
  const envPath = path.join(root, '.env');
  const env = {};
  if (!fs.existsSync(envPath)) return env;
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let val = trimmed.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

function val(env, key) {
  return env[key] || process.env[key] || '';
}

const fileEnv = loadEnvFile();
const config = {
  apiKey: val(fileEnv, 'REACT_APP_FIREBASE_API_KEY'),
  authDomain: val(fileEnv, 'REACT_APP_FIREBASE_AUTH_DOMAIN'),
  projectId: val(fileEnv, 'REACT_APP_FIREBASE_PROJECT_ID'),
  storageBucket: val(fileEnv, 'REACT_APP_FIREBASE_STORAGE_BUCKET'),
  messagingSenderId: val(fileEnv, 'REACT_APP_FIREBASE_MESSAGING_SENDER_ID'),
  appId: val(fileEnv, 'REACT_APP_FIREBASE_APP_ID'),
};

const outPath = path.join(root, 'public', '__firebase-sw-config.js');
const banner = '/* Generated by scripts/write-firebase-sw-config.js — do not edit */\n';
fs.writeFileSync(
  outPath,
  `${banner}self.__FIREBASE_CONFIG__ = ${JSON.stringify(config)};\n`,
);
